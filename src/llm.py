"""Groq LLM Client Wrapper with retry and exponential backoff.

This module provides a safe, reliable interface to Groq's API.
It handles:
1. Client initialization from central config
2. Automatic retries on rate limits (HTTP 429) and network timeouts
3. Exponential backoff to avoid hammering the endpoint
4. Clear error messages without leaking secret keys
"""

import time
import logging
from typing import Optional, List, Dict, Any
from groq import Groq, RateLimitError, APIConnectionError, InternalServerError
from src.config import GROQ_API_KEY, LLM_MODEL_FAST, LLM_MODEL_SMART

# Set up logging for LLM interactions
logger = logging.getLogger(__name__)


def get_groq_client() -> Groq:
    """Initialize and return a Groq client instance using the configured API key."""
    if not GROQ_API_KEY:
        raise ValueError(
            "GROQ_API_KEY is not set. Please add it to your .env file."
        )
    return Groq(api_key=GROQ_API_KEY)


def chat_completion(
    messages: List[Dict[str, str]],
    model: str = LLM_MODEL_FAST,
    temperature: float = 0.0,
    max_tokens: int = 1024,
    max_retries: int = 3,
    initial_delay: float = 2.0,
    timeout: float = 30.0,
) -> str:
    """Send a chat completion request to Groq with retry and exponential backoff.

    Args:
        messages: List of message dictionaries, e.g. [{"role": "user", "content": "Hello"}]
        model: Model name to invoke (defaults to LLM_MODEL_FAST)
        temperature: Sampling temperature (0.0 for deterministic, factual outputs)
        max_tokens: Maximum number of tokens in the response
        max_retries: Number of retry attempts on transient errors / rate limits
        initial_delay: Initial sleep duration in seconds before the first retry
        timeout: Maximum seconds to wait per request

    Returns:
        The text response generated by the LLM.

    Raises:
        RuntimeError if all retries are exhausted.
    """
    client = get_groq_client()
    delay = initial_delay

    for attempt in range(1, max_retries + 1):
        try:
            response = client.chat.completions.create(
                model=model,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                timeout=timeout,
            )
            content = response.choices[0].message.content
            return content.strip() if content else ""

        except RateLimitError as e:
            logger.warning(
                "Groq RateLimitError on attempt %d/%d: %s. Retrying in %.1fs...",
                attempt,
                max_retries,
                e,
                delay,
            )
            if attempt == max_retries:
                raise RuntimeError(
                    f"Groq rate limit exceeded after {max_retries} attempts."
                ) from e
            time.sleep(delay)
            delay *= 2  # Exponential backoff

        except (APIConnectionError, InternalServerError) as e:
            logger.warning(
                "Groq connection or server error on attempt %d/%d: %s. Retrying in %.1fs...",
                attempt,
                max_retries,
                e,
                delay,
            )
            if attempt == max_retries:
                raise RuntimeError(
                    f"Groq connection failed after {max_retries} attempts."
                ) from e
            time.sleep(delay)
            delay *= 2

        except Exception as e:
            # Non-retryable error (e.g. invalid request format, bad auth)
            raise RuntimeError(f"Unexpected Groq API error: {e}") from e

    raise RuntimeError("Failed to complete request after maximum retries.")


def simple_prompt(
    user_prompt: str,
    system_prompt: Optional[str] = None,
    model: str = LLM_MODEL_FAST,
    temperature: float = 0.0,
    max_tokens: int = 1024,
) -> str:
    """Convenience helper to query an LLM with a single user prompt and optional system message."""
    messages = []
    if system_prompt:
        messages.append({"role": "system", "content": system_prompt})
    messages.append({"role": "user", "content": user_prompt})

    return chat_completion(
        messages=messages,
        model=model,
        temperature=temperature,
        max_tokens=max_tokens,
    )
